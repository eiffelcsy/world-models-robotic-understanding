@register("backend", "local_dir")
class LocalDir(VideoBackend):
    """Adopt clips that were generated somewhere else.

        type: local_dir
        params:
          root: ../veo/runs/pilot
          pattern: "{probe}/{sample_id}.mp4"

    No API, no key, no cost. Three things it is for:

      - a model with only a web UI, where the clips arrive by hand;
      - recovering the output of a run that was interrupted, since this pipeline
        does not resume a job it abandoned;
      - testing the whole chain — generation through manifest through scoring —
        offline, which is how every change here should be verified first.

    A frame with no matching file is `skipped`, not an error: a partially
    populated directory is the normal state of hand collection.
    """

    def __init__(self, root: str, pattern: str = "{probe}/{sample_id}.mp4", link: bool = False) -> None:
        super().__init__(root=root, pattern=pattern, link=link)

    def _source(self, request: Request) -> Path:
        return Path(self.root) / self.pattern.format(probe=request.probe, sample_id=request.sample_id)

    def submit(self, request: Request) -> str:
        source = self._source(request)
        if not source.exists():
            raise ClipUnavailable(f"no clip to adopt at {source}")
        return str(source)

    def wait(self, job_id: str, request: Request) -> dict:
        return {"source": job_id}

    def fetch(self, result: dict, request: Request) -> Path:
        source = Path(result["source"])
        ensure_dir(request.dest.parent)
        if request.dest.exists():
            request.dest.unlink()
        if self.link:
            request.dest.symlink_to(source.resolve())
        else:
            shutil.copy2(source, request.dest)
        return request.dest

    def describe(self) -> dict:
        return {**super().describe(), "adopted_from": str(self.root)}
