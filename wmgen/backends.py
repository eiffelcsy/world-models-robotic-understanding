@register("backend", "command")
class Command(VideoBackend):
    """A local or self-hosted model, behind a templated command line.

        type: command
        params:
          model_id: nvidia/Cosmos-Predict2
          command: ["python", "-m", "cosmos.generate",
                    "--image", "{image}", "--prompt", "{prompt}", "--out", "{out}"]
          timeout_s: 1800

    Every field of the request is available as a placeholder; `{out}` is where
    the command must write its mp4. Running an open-source checkpoint this way
    keeps torch and its checkpoints out of wmgen entirely — the same reason
    `modules/instance_seg/requirements.txt` is separate from the root one.

    The process is started in `submit` and waited on in `wait`, so a Ctrl-C
    between them terminates it rather than orphaning it.
    """

    def __init__(self, command: list[str], model_id: str = "", timeout_s: float = 1800.0, cwd: str | None = None):
        super().__init__(command=list(command), model_id=model_id, timeout_s=timeout_s, cwd=cwd)
        self._running: dict[str, subprocess.Popen] = {}

    def submit(self, request: Request) -> str:
        fields = _request_fields(request)
        argv = [str(_fill(arg, fields)) for arg in self.command]
        ensure_dir(request.dest.parent)
        log.debug("  $ %s", " ".join(argv))
        process = subprocess.Popen(
            argv,
            cwd=self.cwd,
            stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
            text=True,
        )
        job_id = f"pid:{process.pid}"
        self._running[job_id] = process
        return job_id

    def wait(self, job_id: str, request: Request) -> dict:
        process = self._running.pop(job_id)
        try:
            output, _ = process.communicate(timeout=self.timeout_s)
        except subprocess.TimeoutExpired:
            process.kill()
            process.communicate()
            raise TimeoutError(f"command still running after {self.timeout_s}s") from None
        if process.returncode != 0:
            tail = "\n".join((output or "").strip().splitlines()[-15:])
            raise IOError(f"command exited {process.returncode}:\n{tail}")
        return {"returncode": process.returncode, "output": (output or "")[-2000:]}

    def fetch(self, result: dict, request: Request) -> Path:
        if not request.dest.exists():
            raise IOError(f"command finished but wrote no video at {request.dest}")
        return request.dest


