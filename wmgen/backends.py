def _expand_env(value: str) -> str:
    """Expand `${VAR}` from the environment, loudly.

    An API key that is missing must not travel as the literal string
    `${GEMINI_API_KEY}` and come back as a 401 an hour later.
    """

    def replace(match: re.Match) -> str:
        name = match.group(1)
        if name not in os.environ:
            raise KeyError(
                f"backend config refers to ${{{name}}}, which is not set in the environment. "
                f"Export it before running; never put a key in backend.yaml."
            )
        return os.environ[name]

    return _ENV.sub(replace, value)


def _fill(node: Any, fields: dict[str, Any]) -> Any:
    """Substitute `{placeholder}` through a nested JSON structure.

    A string that is *exactly* one placeholder takes that field's real type, so
    `durationSeconds: "{duration_s}"` sends the number 8 rather than the string
    "8" — most APIs reject the latter. A placeholder inside a longer string
    formats into it as text.

    Keys whose value comes out None are dropped, so an unset `seed` is an absent
    field rather than an explicit null.
    """
    if isinstance(node, dict):
        filled = {k: _fill(v, fields) for k, v in node.items()}
        return {k: v for k, v in filled.items() if v is not None}
    if isinstance(node, list):
        return [_fill(v, fields) for v in node]
    if not isinstance(node, str):
        return node

    node = _expand_env(node)
    exact = re.fullmatch(r"\{([A-Za-z_][A-Za-z0-9_]*)\}", node)
    if exact:
        if exact.group(1) not in fields:
            raise KeyError(f"backend config has no value for {{{exact.group(1)}}}")
        return fields[exact.group(1)]
    try:
        return node.format_map(fields)
    except KeyError as exc:
        raise KeyError(f"backend config has no value for {exc} in {node!r}") from None


def _dig(obj: Any, path: str) -> Any:
    """Read `a.b[0].c` out of a decoded JSON response.

    An index may also be a match, `steps[type=model_output]`: the first item of
    the list whose `type` is `model_output`. Some APIs return a list whose order
    is not fixed (a "thought" step that may or may not come before the output),
    so a position would point at the wrong item.

    Returns None for a path that is not there, because "not there yet" is the
    normal state of a job being polled.
    """
    for part in path.split("."):
        while part.endswith("]"):
            part, _, index = part[:-1].partition("[")
            if part:
                obj = obj.get(part) if isinstance(obj, dict) else None
                part = ""
            if obj is None:
                return None
            if "=" in index:
                key, _, value = index.partition("=")
                matches = [item for item in obj if isinstance(item, dict) and str(item.get(key)) == value] if isinstance(obj, list) else []
                if not matches:
                    return None
                obj = matches[0]
                continue
            try:
                obj = obj[int(index)]
            except (IndexError, TypeError, ValueError):
                return None
        if part:
            if not isinstance(obj, dict):
                return None
            obj = obj.get(part)
        if obj is None:
            return None
    return obj


NEGATIVE_LEAD = "The clip must not contain any of the following:"


def _with_negative(text: str, negative: str) -> str:
    text, negative = text.strip(), " ".join(negative.split())
    if not negative:
        return text
    return f"{text}\n\n{NEGATIVE_LEAD} {negative.rstrip('.')}."


def _request_fields(request: Request) -> dict[str, Any]:
    """Everything a backend template can refer to."""
    image = request.frame.path.read_bytes()
    mime = mimetypes.guess_type(str(request.frame.path))[0] or "image/png"
    return {
        "sample_id": request.sample_id,
        "probe": request.probe,
        "prompt": request.prompt.text,
        "negative": request.prompt.negative,
        # For a model with no negative-prompt field (Gemini Omni): the negative
        # rides at the end of the prompt, in one fixed wording for every arm.
        "prompt_and_negative": _with_negative(request.prompt.text, request.prompt.negative),
        "image": str(request.frame.path),
        "image_b64": base64.b64encode(image).decode("ascii"),
        "image_mime": mime,
        "out": str(request.dest),
        # No seed set (`seed_base: null`): `{seed}` fills as None and _fill drops
        # the key, rather than failing on a missing placeholder.
        "seed": None,
        **request.video,
    }


