def _http(
    url: str,
    *,
    method: str = "GET",
    headers: dict[str, str] | None = None,
    body: Any = None,
    retries: int = 3,
    timeout: float = 120.0,
) -> bytes:
    """One HTTP call, retrying the failures that are worth retrying.

    429 and 5xx are transient and are retried with backoff; a 4xx is a wrong
    request and is raised immediately, because retrying a malformed body just
    spends more time arriving at the same error.
    """
    data = json.dumps(body).encode("utf-8") if body is not None else None
    request = urllib.request.Request(url, data=data, method=method)
    for key, value in (headers or {}).items():
        request.add_header(key, value)
    if data is not None:
        request.add_header("Content-Type", "application/json")

    delay = 2.0
    for attempt in range(1, max(1, retries) + 1):
        try:
            with urllib.request.urlopen(request, timeout=timeout) as response:
                return response.read()
        except urllib.error.HTTPError as exc:
            detail = exc.read()[:500].decode("utf-8", "replace")
            transient = exc.code == 429 or exc.code >= 500
            if not transient or attempt == retries:
                raise IOError(f"{method} {url} -> HTTP {exc.code}: {detail}") from None
            log.warning("  HTTP %s from %s, retrying in %.0fs", exc.code, url, delay)
        except urllib.error.URLError as exc:
            if attempt == retries:
                raise IOError(f"{method} {url} -> {exc.reason}") from None
            log.warning("  %s, retrying in %.0fs", exc.reason, delay)
        time.sleep(delay)
        delay *= 2
    raise IOError(f"{method} {url}: exhausted {retries} attempts")


@register("backend", "http_job")
class HttpJob(VideoBackend):
    """Submit a generation job over REST, poll it, download the result.

    The whole vendor contract is four blocks of YAML — see
    `backends/omni12/backend.yaml` for a worked example:

        submit: {url, method, body, job_id_path}
        poll:   {url, method?, body?, interval_s, timeout_s, done_path, error_path,
                 done_values?, failed_values?}
        fetch:  {url_path}  or  {b64_path}

    Without `done_values` the job is done once `done_path` holds anything true
    (an operation's `done: true`). With it, `done_path` is a status string: done
    when it is one of `done_values`, failed when it is one of `failed_values`.
    Paths may match list items by field, `steps[type=model_output]`.
        headers: {"x-goog-api-key": "${GEMINI_API_KEY}"}

    Strings anywhere in those blocks are templated with the request (`{prompt}`,
    `{image_b64}`, `{duration_s}`, …); `poll.url` and `fetch` additionally see
    `{job_id}`. `${ENV_VAR}` is read from the environment, so no key is ever
    written into the repo.

    Pointing this at a different vendor is editing YAML. That is the whole
    reason it exists, and the reason its defaults are Veo-shaped rather than
    hard-coded.
    """

    def __init__(
        self,
        submit: dict[str, Any],
        poll: dict[str, Any],
        fetch: dict[str, Any],
        headers: dict[str, str] | None = None,
        model_id: str = "",
        retries: int = 3,
    ) -> None:
        super().__init__(headers=headers or {}, model_id=model_id, retries=retries)
        # `submit` and `fetch` are method names, so these three blocks are held
        # under `_spec` attributes rather than splatted on like other params.
        self.submit_spec, self.poll_spec, self.fetch_spec = submit, poll, fetch
        self.params.update({"submit": submit, "poll": poll, "fetch": fetch})

    def _headers(self, fields: dict[str, Any]) -> dict[str, str]:
        return {k: str(_fill(v, fields)) for k, v in self.headers.items()}

    def submit(self, request: Request) -> str:
        fields = _request_fields(request)
        spec = self.submit_spec
        raw = _http(
            str(_fill(spec["url"], fields)),
            method=spec.get("method", "POST"),
            headers=self._headers(fields),
            body=_fill(spec.get("body"), fields),
            retries=self.retries,
        )
        response = json.loads(raw)
        job_id = _dig(response, spec.get("job_id_path", "name"))
        if not job_id:
            raise IOError(
                f"submit returned no job id at '{spec.get('job_id_path', 'name')}': "
                f"{json.dumps(response)[:400]}"
            )
        return str(job_id)

    def wait(self, job_id: str, request: Request) -> dict:
        fields = {**_request_fields(request), "job_id": job_id}
        spec = self.poll_spec
        url = str(_fill(spec["url"], fields))
        interval = float(spec.get("interval_s", 10))
        deadline = time.time() + float(spec.get("timeout_s", 900))
        done_path = spec.get("done_path", "done")
        error_path = spec.get("error_path", "error")
        done_values = spec.get("done_values")
        failed_values = list(spec.get("failed_values") or [])

        while True:
            response = json.loads(
                _http(
                    url,
                    method=spec.get("method", "GET"),
                    headers=self._headers(fields),
                    body=_fill(spec.get("body"), fields),  # a POST poll (Vertex fetchPredictOperation)
                    retries=self.retries,
                )
            )
            failure = _dig(response, error_path)
            if failure:
                raise IOError(f"backend job failed: {json.dumps(failure)[:400]}")
            state = _dig(response, done_path)
            if done_values is None:
                if state:  # a flag: Vertex and Gemini operations set `done: true`
                    return response
            else:  # a status string: the Interactions API sets `status: "completed"`
                if state in failed_values:
                    raise IOError(f"backend job {job_id} ended as {state!r}: {json.dumps(response)[:400]}")
                if state in done_values:
                    return response
            if time.time() > deadline:
                raise TimeoutError(f"job {job_id} still running after {spec.get('timeout_s', 900)}s")
            time.sleep(interval)

    def fetch(self, result: dict, request: Request) -> Path:
        fields = _request_fields(request)
        spec = self.fetch_spec
        ensure_dir(request.dest.parent)

        if "b64_path" in spec:
            payload = _dig(result, spec["b64_path"])
            if not payload:
                raise IOError(f"no video at '{spec['b64_path']}' in {json.dumps(result)[:400]}")
            request.dest.write_bytes(base64.b64decode(payload))
            return request.dest

        url = _dig(result, spec["url_path"])
        if not url:
            raise IOError(f"no video url at '{spec['url_path']}' in {json.dumps(result)[:400]}")
        headers = {k: str(_fill(v, fields)) for k, v in (spec.get("headers") or self.headers).items()}
        request.dest.write_bytes(_http(str(_fill(str(url), fields)), headers=headers, retries=self.retries))
        return request.dest


