"""The world models.

wmeval is model-agnostic because it never calls a generator. wmgen has to call
one, so it is model-agnostic a different way: **calling a generator is
configuration, not code.** Three general mechanisms ship here, and a world model
is normally a `backends/<name>/backend.yaml` choosing one and filling it in:

    http_job    submit -> poll -> fetch over REST. Most hosted video APIs.
    command     a templated subprocess. Local and self-hosted open-source models.
    local_dir   adopt clips generated by hand elsewhere. Costs nothing, needs no
                keys, and is how the pipeline is tested end to end offline.

Writing Python is the escape hatch, not the path. A vendor whose SDK cannot be
expressed as an HTTP job adds `backends/<name>/backend.py` registering a class
in the `backend` family, exactly as a probe adds `gt.py` — and its
`backend.yaml` then names that type.

`http_job` is built on stdlib `urllib`, so adding a world model adds no
dependency. That is the same trade the eval side makes in
`modules/instance_seg/metrics.py`, where a greedy match avoids pulling in scipy.
"""

